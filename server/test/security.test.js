test('validated record writes preserve other records and detect concurrent changes', async () => {
    const response = await request('/notice', { admin: true, method: 'POST', headers: json(), body: JSON.stringify({ text: 'One', text_bn: 'One' }) });
    assert.equal(response.status, 201); const item = await response.json();
    const options = { admin: true, method: 'PUT', headers: json(), body: JSON.stringify({ text: 'Two', __v: 0 }) };
    const [first, second] = await Promise.all([request(`/notice/${item.id}`, options), request(`/notice/${item.id}`, options)]);
    assert.deepEqual([first.status, second.status].sort(), [200,409]);
    assert.equal(await Notice.countDocuments({ id: 'keep' }), 1);
    assert.equal((await Notice.findOne({ id: item.id })).__v, 1);
    assert.equal((await request(`/notice/${item.id}`, { admin: true, method: 'DELETE', headers: { 'If-Match': '0' } })).status, 409);
    assert.equal((await request(`/notice/${item.id}`, { admin: true, method: 'DELETE', headers: { 'If-Match': '1' } })).status, 200);
});
